/**
 * Generate lib/icons.generated.ts with only the game-icons.net icons actually used, so the bundle
 * doesn't ship all 4,000 of them. Run after changing content or UI icons: pnpm --filter @textrpg/web icons
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const gi = require("react-icons/gi");
const dataDir = join(here, "../../../packages/content/data");

const names = new Set();
for (const file of readdirSync(dataDir)) {
  const text = readFileSync(join(dataDir, file), "utf8");
  for (const match of text.matchAll(/"icon":\s*"(Gi\w+)"/g)) names.add(match[1]);
}
// Icons referenced directly by the UI code.
for (const dir of ["components", "app", "lib"]) {
  const walk = (path) => {
    for (const entry of readdirSync(path, { withFileTypes: true })) {
      const full = join(path, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (/\.tsx?$/.test(entry.name) && !entry.name.includes("generated")) {
        for (const match of readFileSync(full, "utf8").matchAll(/["'](Gi[A-Z]\w+)["']/g)) names.add(match[1]);
      }
    }
  };
  walk(join(here, "..", dir));
}

const missing = [...names].filter((n) => typeof gi[n] !== "function");
if (missing.length) {
  console.error("Unknown icons:", missing.join(", "));
  process.exit(1);
}
const sorted = [...names].sort();
writeFileSync(
  join(here, "../lib/icons.generated.ts"),
  `// Generated by scripts/gen-icons.mjs — do not edit.\nimport {\n${sorted.map((n) => `  ${n},`).join("\n")}\n} from "react-icons/gi";\n\nexport const ICONS = {\n${sorted.map((n) => `  ${n},`).join("\n")}\n};\n\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`${sorted.length} icons`);
